#!/usr/bin/env python3
"""Full 5-codec post-training analysis pipeline.

Stages (each can be skipped with --skip-{stage}):
  0. clean      — Remove stale token / analysis dirs  (opt-in: --clean)
  1. discover    — Auto-discover checkpoints for all 5 codecs
  2. encode      — Encode sinusoid test signals (amp / phase / temporal)
  3. jacobian    — Compute subsampled Jacobian norms (~20 min per model on A40)
  4. report      — Run report_combined_sensitivity.py per model → PDF
  5. egfx        — Encode + compute + analyse EGFx pairs
  6. multi       — Run report_multi_codec_sensitivity.py → multi-codec PDF
    7. tables      — Run generate_dissertation_tables.py → 8 analysis CSVs

Usage:
    python run_analysis.py                    # full pipeline
    python run_analysis.py --clean            # wipe stale tokens/analysis first
    python run_analysis.py --clean --yes      # same, skip confirmation prompt
    python run_analysis.py --skip-svd        # skip SVD stage (rarely needed)
    python run_analysis.py --only-tables      # only (re-)generate CSVs
    python run_analysis.py --device cpu       # CPU fallback

Checkpoints are auto-discovered from default training output paths.
Override with explicit flags:
    --encodec-ckpt    Encodec/checkpoints_multi_dataset/...
    --q2d2-ckpt       Q2D2/outputs/...
    --hificodec-ckpt  hificodec/egs/hificodec_fsd50k
    --st-ckpt         results/speechtokenizer_fsd50k/SpeechTokenizer_best_dev.pt
    --dac-ckpt        descript-audio-codec/ckpt/fsd50k_fsq
"""
