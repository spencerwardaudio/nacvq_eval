def stage_egfx(ckpts: dict, device: str, results: dict) -> None:
    print("\n" + "=" * 65)
    print("STAGE 5 — EGFx encode + metrics + analysis")
    print("=" * 65)

    egfx_pairs = _DS / "egfx" / "effect_pairs.json"
    legacy_pairs = _DS / "ecdc" / "egfx_pairs.json"
    if not egfx_pairs.exists() and legacy_pairs.exists():
        egfx_pairs = legacy_pairs

    if not egfx_pairs.exists():
        print(f"  [SKIP] EGFx pairs file not found: {_DS / 'egfx' / 'effect_pairs.json'}")
        return

    tokens_dir = _DS / "audio_tokens" / "egfx"
    metrics_out = _ANA / "egfx_metrics.json"
    egfx_pdf    = _ANA / "egfx_report.pdf"

    # Encode
    codecs_with_ckpts = [c for c in ckpts if ckpts[c] is not None]
    encode_cmd = [
        sys.executable, str(_TOK / "egfx_encode.py"),
        "--pairs", str(egfx_pairs),
        "--codecs", *codecs_with_ckpts,
        "--output-dir", str(tokens_dir),
        "--device", device,
        "--max-per-category", "25",
    ]
    for codec, ckpt in ckpts.items():
        if ckpt is not None:
            encode_cmd += [f"--{codec.replace('_', '-')}-checkpoint", str(ckpt)]

    ok = _run(encode_cmd, "EGFx encode")
    results["egfx_encode"] = ok
    if not ok:
        return

    # Metrics
    ok = _run([
        sys.executable, str(_TOK / "egfx_metrics.py"),
        "--tokens-dir", str(tokens_dir),
        "--output", str(metrics_out),
    ], "EGFx metrics")
    results["egfx_metrics"] = ok
    if not ok:
        return

    # Analyze
    ok = _run([
        sys.executable, str(_TOK / "egfx_analyze.py"),
        "--metrics", str(metrics_out),
        "--output", str(egfx_pdf),
    ], "EGFx analyze")
    results["egfx_analyze"] = ok
    if ok:
        _assert_file(egfx_pdf, "EGFx PDF", min_bytes=5_000)


