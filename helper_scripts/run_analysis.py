def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__,
                                 formatter_class=argparse.RawDescriptionHelpFormatter)

    # Clean flag
    ap.add_argument("--clean", action="store_true",
                    help="Remove stale token/analysis dirs before encoding (opt-in)")
    ap.add_argument("--yes", action="store_true",
                    help="Skip confirmation prompt when --clean is set")

    # Skip flags
    ap.add_argument("--skip-encode",    action="store_true")
    ap.add_argument("--skip-svd",       action="store_true",
                    help="Skip SVD(ΔZ) EVR stage (runs in seconds, rarely needed)")
    ap.add_argument("--skip-jacobian",  action="store_true",  # kept for backward compat
                    help=argparse.SUPPRESS)
    ap.add_argument("--skip-report",    action="store_true")
    ap.add_argument("--skip-egfx",      action="store_true")
    ap.add_argument("--skip-multi",     action="store_true")
    ap.add_argument("--only-tables",    action="store_true",
                    help="Skip all stages except table generation")

    # Explicit checkpoint overrides
    ap.add_argument("--encodec-ckpt",   default="")
    ap.add_argument("--q2d2-ckpt",      default="")
    ap.add_argument("--hificodec-ckpt", default="")
    ap.add_argument("--st-ckpt",        default="")
    ap.add_argument("--dac-ckpt",       default="")

    ap.add_argument("--device", default="cuda")

    args = ap.parse_args()

    _ANA.mkdir(parents=True, exist_ok=True)

    print("\n" + "=" * 65)
    print("  5-Codec Post-Training Analysis Pipeline")
    print("=" * 65)

    # Stage 1: Discover checkpoints
    ckpts = discover_checkpoints(args)
    print("\nSTAGE 1 — Checkpoint discovery")
    for codec, path in ckpts.items():
        status = PASS if path is not None else FAIL
        print(f"  {status} {codec:16s} {path or '(not found)'}")

    found = sum(1 for p in ckpts.values() if p is not None)
    assert found > 0, "No checkpoints found. Train models first with train_5codecs.sh"  # nothing to analyse without at least one trained model

    results: dict = {
        "checkpoints_found": found,
        "checkpoints_used": {k: str(v) for k, v in ckpts.items() if v is not None},
    }

    if args.only_tables:
        stage_tables(results, ckpts)
        return

    # Stage 0: Clean stale outputs (opt-in)
    if args.clean:
        stage_clean(yes=args.yes)

    # Stage 2: Encode tokens
    if not args.skip_encode:
        stage_encode(ckpts, args.device, results)

    # Stage 3: SVD(ΔZ) EVR metrics
    if not args.skip_svd:
        stage_svd(ckpts, results)

    # Stage 4: Per-model sensitivity PDFs
    if not args.skip_report:
        stage_reports(ckpts, args.device, results)

    # Stage 5: EGFx
    if not args.skip_egfx:
        stage_egfx(ckpts, args.device, results)

    # Stage 6: Multi-codec PDF
    if not args.skip_multi:
        stage_multi_report(ckpts, results)

    if not args.skip_svd:  # centroid export reads SVD-stage token files; skip if SVD was skipped
        _export_centroids(ckpts, results)

    # Stage 8: Dissertation tables
    stage_tables(results, ckpts)

    # ── Final summary ─────────────────────────────────────────────────────
    print("\n" + "=" * 65)
    print("  Pipeline summary")
    print("=" * 65)
    passed = sum(1 for k, v in results.items() if v is True)
    failed = sum(1 for k, v in results.items() if v is False)
    for key, val in results.items():
        if isinstance(val, bool):
            print(f"  {'✓' if val else '✗'} {key}")

    n_tables = results.get("tables_count", 0)
    print(f"\n  Checkpoints found : {results['checkpoints_found']} / 5")
    print(f"  Analysis tables     : {n_tables} / 7")
    print(f"  Stages passed : {passed}   failed : {failed}")

    if failed > 0:
        sys.exit(1)


if __name__ == "__main__":
    main()
