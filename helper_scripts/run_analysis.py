def discover_checkpoints(args) -> dict[str, Path | None]:
    ckpts: dict[str, Path | None] = {}

    # Encodec
    if args.encodec_ckpt:
        ckpts["encodec"] = Path(args.encodec_ckpt)
    else:
        # exclude discriminator checkpoints; prefer files named *best*, else latest by mtime
        _enc_all = [p for p in (_PROJ / "Encodec").glob(
            "outputs/**/checkpoints_multi_dataset/*.pt") if "_disc" not in p.stem]  # discriminator files are not the model
        _enc_preferred = [p for p in _enc_all if "best" in p.stem] or _enc_all  # fall back to all if no *best* file
        ckpts["encodec"] = sorted(_enc_preferred, key=lambda p: p.stat().st_mtime)[-1] if _enc_preferred else None

    # Q2D2
    if args.q2d2_ckpt:
        ckpts["q2d2"] = Path(args.q2d2_ckpt)
    else:
        ckpts["q2d2"] = _glob_latest(
            "outputs/lightning_logs/version_*/checkpoints/Q2D2_best.ckpt",
            _PROJ / "Q2D2",
        )

    # HiFiCodec — checkpoint dir (contains g_XXXXXXXX files)
    if args.hificodec_ckpt:
        ckpts["hificodec"] = Path(args.hificodec_ckpt)
    else:
        hfc_dir = _PROJ / "hificodec" / "egs" / "hificodec_fsd50k"
        ckpts["hificodec"] = hfc_dir if hfc_dir.exists() and list(hfc_dir.glob("g_*")) else None  # g_* files are the trained generator weights

    # SpeechTokenizer
    if args.st_ckpt:
        ckpts["speechtokenizer"] = Path(args.st_ckpt)
    else:
        st_path = _PROJ / "results" / "speechtokenizer_fsd50k" / "SpeechTokenizer_best_dev.pt"
        ckpts["speechtokenizer"] = st_path if st_path.exists() else None

    # DAC-FSQ
    if args.dac_ckpt:
        ckpts["dac_fsq"] = Path(args.dac_ckpt)
    else:
        dac_dir = _PROJ / "descript-audio-codec" / "ckpt" / "fsd50k_fsq" / "best"
        ckpts["dac_fsq"] = dac_dir if dac_dir.exists() else None

    return ckpts


