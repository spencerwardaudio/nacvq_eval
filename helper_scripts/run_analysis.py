_ENCODE_SCRIPTS = {
    "hificodec":        _TOK / "encode_hificodec_tokens.py",
    "speechtokenizer":  _TOK / "encode_speechtokenizer_tokens.py",
    "dac_fsq":          _TOK / "encode_dac_fsq_tokens.py",
}

_BW_TAGS = {
    "encodec":          "24.0",
    "q2d2":             "9.8",
    "hificodec":        "HFC",
    "speechtokenizer":  "ST",
    "dac_fsq":          "FSQ",
}

_ENCODE_CONFIGS = {
    "hificodec": {
        "config": str(_PROJ / "hificodec" / "egs" / "HiFi-Codec-24k-320d" / "config_24k_320d.json"),
    },
    "speechtokenizer": {
        "config": str(_PROJ / "SpeechTokenizer" / "config" / "fsd50k_cfg.json"),
    },
    "dac_fsq": {},
}


def stage_encode(ckpts: dict, device: str, results: dict) -> None:
    print("\n" + "=" * 65)
    print("STAGE 2 — Encode sinusoid test tokens")
    print("=" * 65)

    # Encodec / Q2D2 use run_pipeline.py (existing per-model pipeline)
    for codec in ("encodec", "q2d2"):
        ckpt = ckpts.get(codec)
        if ckpt is None:
            print(f"  [SKIP] {codec}: no checkpoint")
            continue
        for flag, label in [
            ("--self-amp-test",      "amp"),
            ("--self-phase-test",    "phase"),
            ("--sine-temporal-test", "temporal"),
        ]:
            bw = _BW_TAGS[codec]
            model_name = "multi_dataset_encodec" if codec == "encodec" else "q2d2"
            cmd = [
                sys.executable, str(_TOK / "run_pipeline.py"),
                flag,
                "--model", model_name,
                "--checkpoint", str(ckpt),
                "--bandwidth", str(bw),
                "--device", device,
                "--skip-generate",
            ]
            ok = _run(cmd, f"{codec} {label} tokens")
            results[f"encode_{codec}_{label}"] = ok

    # HiFiCodec / SpeechTokenizer / DAC-FSQ use dedicated encode scripts
    for codec, script in _ENCODE_SCRIPTS.items():
        ckpt = ckpts.get(codec)
        if ckpt is None:
            print(f"  [SKIP] {codec}: no checkpoint")
            continue
        cmd = [sys.executable, str(script), "--checkpoint", str(ckpt),
               "--device", device, "--bw-tag", _BW_TAGS[codec]]
        cfg = _ENCODE_CONFIGS.get(codec, {})
        if "config" in cfg:
            cmd += ["--config", cfg["config"]]
        ok = _run(cmd, f"{codec} encode tokens")
        results[f"encode_{codec}"] = ok


