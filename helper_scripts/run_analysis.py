def stage_clean(yes: bool) -> None:
    print("\n" + "=" * 65)
    print("STAGE 0 — Clean stale tokens and analysis outputs")
    print("=" * 65)

    targets: list[Path] = []

    tokens_root = _DS / "audio_tokens"
    for name in _AUDIO_TOKEN_STALE:
        p = tokens_root / name
        if p.exists():
            targets.append(p)

    for name in _ANALYSIS_STALE:
        p = _ANA / name
        if p.exists():
            targets.append(p)

    for name in _ANALYSIS_STALE_FILES:
        p = _ANA / name
        if p.exists():
            targets.append(p)

    if not targets:
        print("  Nothing to clean — workspace already tidy.")
        return

    print(f"\n  The following {len(targets)} items will be permanently deleted:")
    total_bytes = 0
    for p in targets:
        if p.is_dir():
            size = sum(f.stat().st_size for f in p.rglob("*") if f.is_file())
            print(f"    [DIR]  {p.relative_to(_PROJ)}  ({size // (1024*1024)} MB)")
        else:
            size = p.stat().st_size
            print(f"    [FILE] {p.relative_to(_PROJ)}  ({size // 1024} KB)")
        total_bytes += size

    print(f"\n  Total: ~{total_bytes // (1024*1024)} MB")

    if not yes:
        try:
            answer = input("\n  Proceed with deletion? [y/N] ").strip().lower()
        except EOFError:
            answer = ""
        if answer not in ("y", "yes"):
            print("  Aborted. Re-run with --clean --yes to skip this prompt.")
            sys.exit(0)

    n_deleted = 0
    for p in targets:
        try:
            if p.is_dir():
                shutil.rmtree(p)
            else:
                p.unlink()
            print(f"  {PASS} Removed: {p.relative_to(_PROJ)}")
            n_deleted += 1
        except Exception as exc:
            print(f"  {FAIL} Could not remove {p}: {exc}")

    print(f"\n  Cleaned {n_deleted} / {len(targets)} items.")


