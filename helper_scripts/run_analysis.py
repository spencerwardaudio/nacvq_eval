def stage_svd(ckpts: dict, results: dict) -> None:
    """Compute SVD(ΔZ) EVR metrics for all codecs from pre-saved token files.

    No GPU required; finishes in seconds per codec.
    Output: datasets/analysis/svd/{codec}/svd_stats_bw{bw}.json
    """
    print("\n" + "=" * 65)
    print("STAGE 3 — SVD(ΔZ) EVR metrics (all perturbation types)")
    print("=" * 65)

    tokens_root = _DS / "audio_tokens"
    svd_root    = _ANA / "svd"

    _model_name = {
        "encodec":         "multi_dataset_encodec",
        "q2d2":            "q2d2",
        "hificodec":       "hificodec",
        "speechtokenizer": "speechtokenizer",
        "dac_fsq":         "dac_fsq",
    }

    for codec, ckpt in ckpts.items():
        if ckpt is None:
            print(f"  [SKIP] {codec}: no checkpoint")
            continue
        subdir = "" if codec in ("encodec", "q2d2") else codec
        if subdir:
            amp_root  = tokens_root / subdir / "dsp_self_amp"
            phase_root = tokens_root / subdir / "dsp_self_phase"
            temp_root  = tokens_root / subdir / "time_sine"
        else:
            amp_root  = tokens_root / "dsp_self_amp"
            phase_root = tokens_root / "dsp_self_phase"
            temp_root  = tokens_root / "time_sine"

        cmd = [
            sys.executable, str(_TOK / "compute_svd_evr2.py"),
            "--codec",           codec,
            "--checkpoint",      str(ckpt),
            "--model-type",      codec,
            "--bw-tag",          _BW_TAGS[codec],
            "--amp-tokens",      str(amp_root),
            "--phase-tokens",    str(phase_root),
            "--temporal-tokens", str(temp_root),
            "--output-dir",      str(svd_root),
        ]
        ok = _run(cmd, f"{codec} SVD EVR metrics")
        results[f"svd_{codec}"] = ok


